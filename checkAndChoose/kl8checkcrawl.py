    if not line:
        continue

    # 🔥 核心：只取 "次:" 后面的内容
    if "次:" in line:
        # 分割 "次:"，只拿后面部分
        num_part = line.split("次:", 1)[1]
        # 提取数字
        line_nums = set(re.findall(r'\d+', num_part))
        # 计算命中
        hit = sorted(target_nums & line_nums, key=int)

        if hit:
            print(f"{num_part}")
            print(f"  命中：{hit} → 共 {len(hit)} 个\n")